function renderFAQ() {
  const box = $('#faql');
  box.innerHTML = FAQ.map(([q, a], i) => `<details class="q rv" style="--d:${i * 0.06}s"><summary>${esc(q[LI()])}</summary><div class="qa"><p>${esc(a[LI()])}</p></div></details>`).join('');
  $$('details.q', box).forEach(d => {
    const qa = $('.qa', d);
    $('summary', d).addEventListener('click', e => {
      e.preventDefault(); if (REDUCED) { d.open = !d.open; return; }
      if (d.open) { const h = qa.offsetHeight; qa.animate([{ height: h + 'px', opacity: 1 }, { height: '0px', opacity: 0 }], { duration: 260, easing: 'ease' }).onfinish = () => { d.open = false; }; }
      else { d.open = true; const h = qa.offsetHeight; qa.animate([{ height: '0px', opacity: 0 }, { height: h + 'px', opacity: 1 }], { duration: 360, easing: 'cubic-bezier(.16,1,.3,1)' }); }
    });
  });
}

